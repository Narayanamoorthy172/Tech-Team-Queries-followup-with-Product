-- Required for gen_random_uuid()
create extension if not exists "pgcrypto";

-- -----------------------------------------------------------------------------
-- profiles
-- One row per user, created automatically when someone signs up.
-- Stores app-specific preferences that aren't part of Supabase Auth itself.
-- -----------------------------------------------------------------------------
create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email text,
  full_name text,
  default_followup_days integer not null default 3,
  timezone text not null default 'Asia/Kolkata',
  date_format text not null default 'DD/MM/YYYY',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.profiles is 'One row per authenticated user; app-level profile and preferences.';

-- -----------------------------------------------------------------------------
-- requests
-- The core entity: one "Product Request" = one email/issue conversation
-- with the Product Team.
-- -----------------------------------------------------------------------------
create table if not exists public.requests (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,

  -- Human-friendly sequential ID like REQ-001, REQ-002, ...
  seq bigint generated by default as identity,
  code text generated always as ('REQ-' || lpad(seq::text, 3, '0')) stored,

  -- Basic information
  title text not null,
  description text,
  product text not null,
  request_type text not null,
  priority text not null default 'medium'
    check (priority in ('low', 'medium', 'high', 'critical')),
  status text not null default 'draft'
    check (status in (
      'draft', 'sent', 'waiting_for_product', 'product_reviewing',
      'in_progress', 'eta_provided', 'waiting_for_release',
      'resolved', 'closed', 'rejected', 'cancelled'
    )),
  owner_contact text,

  -- Email information
  email_subject text,
  product_team_email text,
  original_email_date date,
  email_thread_ref text,
  email_url text,

  -- Tracking information
  eta_date date,
  next_follow_up_date date,
  last_follow_up_date date,
  follow_up_count integer not null default 0,
  resolution_date date,

  -- Additional information
  notes text,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint title_not_blank check (btrim(title) <> '')
);

comment on table public.requests is 'One row per Product Request (an email/issue conversation with the Product Team).';

-- -----------------------------------------------------------------------------
-- request_activity
-- Append-only timeline of everything that happened to a request.
-- -----------------------------------------------------------------------------
create table if not exists public.request_activity (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null references public.requests (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  activity_type text not null,
  description text not null,
  metadata jsonb,
  created_at timestamptz not null default now()
);

comment on table public.request_activity is 'Append-only activity/timeline entries for a request.';

-- -----------------------------------------------------------------------------
-- follow_ups
-- Individual follow-up reminders tied to a request. next_follow_up_date on
-- the request itself drives the dashboard; this table keeps history of every
-- follow-up scheduled/completed over the life of the request.
-- -----------------------------------------------------------------------------
create table if not exists public.follow_ups (
  id uuid primary key default gen_random_uuid(),
  request_id uuid not null references public.requests (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  due_date date not null,
  status text not null default 'pending'
    check (status in ('pending', 'completed', 'rescheduled', 'cancelled')),
  completed_at timestamptz,
  notes text,
  created_at timestamptz not null default now()
);

comment on table public.follow_ups is 'Individual follow-up reminders/history for a request.';

-- -----------------------------------------------------------------------------
-- tags + request_tags
-- Simple many-to-many tagging.
-- -----------------------------------------------------------------------------
create table if not exists public.tags (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users (id) on delete cascade,
  name text not null,
  created_at timestamptz not null default now(),
  unique (user_id, name)
);

comment on table public.tags is 'Tag vocabulary, scoped per user.';

create table if not exists public.request_tags (
  request_id uuid not null references public.requests (id) on delete cascade,
  tag_id uuid not null references public.tags (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  primary key (request_id, tag_id)
);

comment on table public.request_tags is 'Join table linking requests to tags.';

