-- =============================================================================
-- updated_at trigger — keeps "Last Updated" accurate automatically
-- =============================================================================
create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists trg_profiles_updated_at on public.profiles;
create trigger trg_profiles_updated_at
  before update on public.profiles
  for each row execute function public.set_updated_at();

drop trigger if exists trg_requests_updated_at on public.requests;
create trigger trg_requests_updated_at
  before update on public.requests
  for each row execute function public.set_updated_at();

-- =============================================================================
-- Auto-create a profile row whenever someone signs up
-- =============================================================================
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, email)
  values (new.id, new.email)
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists trg_on_auth_user_created on auth.users;
create trigger trg_on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- =============================================================================
-- Auto-log activity on request creation and key field changes
-- =============================================================================
create or replace function public.log_request_activity()
returns trigger
language plpgsql
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.request_activity (request_id, user_id, activity_type, description)
    values (new.id, new.user_id, 'created', 'Request created');
    return new;
  end if;

  if tg_op = 'UPDATE' then
    if new.status is distinct from old.status then
      insert into public.request_activity (request_id, user_id, activity_type, description)
      values (new.id, new.user_id, 'status_changed',
        'Status changed: ' || old.status || ' -> ' || new.status);
    end if;

    if new.priority is distinct from old.priority then
      insert into public.request_activity (request_id, user_id, activity_type, description)
      values (new.id, new.user_id, 'priority_changed',
        'Priority changed: ' || old.priority || ' -> ' || new.priority);
    end if;

    if new.eta_date is distinct from old.eta_date then
      insert into public.request_activity (request_id, user_id, activity_type, description)
      values (new.id, new.user_id, 'eta_changed',
        case when new.eta_date is null then 'ETA removed'
             else 'ETA set: ' || to_char(new.eta_date, 'FMMonth DD, YYYY') end);
    end if;

    if new.next_follow_up_date is distinct from old.next_follow_up_date then
      insert into public.request_activity (request_id, user_id, activity_type, description)
      values (new.id, new.user_id, 'followup_scheduled',
        case when new.next_follow_up_date is null then 'Next follow-up cleared'
             else 'Next follow-up set: ' || to_char(new.next_follow_up_date, 'FMMonth DD, YYYY') end);
    end if;

    if new.resolution_date is distinct from old.resolution_date and new.resolution_date is not null then
      insert into public.request_activity (request_id, user_id, activity_type, description)
      values (new.id, new.user_id, 'resolved', 'Request marked resolved');
    end if;

    return new;
  end if;

  return null;
end;
$$;

drop trigger if exists trg_requests_log_activity on public.requests;
create trigger trg_requests_log_activity
  after insert or update on public.requests
  for each row execute function public.log_request_activity();

